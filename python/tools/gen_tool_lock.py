"""
Regenerate tool_names.lock: every tool the server publishes in full mode (no extensions), with its
safety hint. Run after adding, renaming or removing a tool, and commit the result:

    python tools/gen_tool_lock.py

A rename or removal must also add an alias in tool_aliases.json (old name -> new name), so skills
and docs that call the old name keep working for one release.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LOCK = os.path.join(ROOT, "tool_names.lock")


def current_lines():
    sys.path.insert(0, ROOT)
    sys.path.insert(0, os.path.join(ROOT, "mcp_server"))
    sys.path.insert(0, os.path.join(ROOT, "mcp_server", "api"))
    os.environ["EPLAN_MCP_EXTENSIONS"] = ""
    from mcp_server import server
    import tool_hints
    app, _, _ = server.build_app(mode="full")
    lines = []
    for name, tool in sorted(app._tool_manager._tools.items()):
        ann = tool.annotations.model_dump(exclude_none=True) if tool.annotations else {}
        lines.append(f"{name}\t{tool_hints.lock_tag(ann)}")
    return lines


def main():
    lines = current_lines()
    with open(LOCK, "w", encoding="utf-8", newline="\n") as f:
        f.write("# Generated by tools/gen_tool_lock.py - one published tool per line: name<TAB>hint\n")
        f.write("\n".join(lines) + "\n")
    print(f"{len(lines)} tools written to {LOCK}")


if __name__ == "__main__":
    main()
